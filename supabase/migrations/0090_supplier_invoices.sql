--      Đọc = `imports.invoices` Xem HOẶC `imports` Xem — xưởng cần đọc liên kết để thấy nhãn "Chờ HĐ /
--      HĐ 936" trên chuyến (R12; file + tiền ẩn ở app, file chặn ở bucket).
--   3. Bucket `supplier-invoice-files` (chủ dự án tạo TRƯỚC trên Dashboard: private, 20 MB) — chỉ
--      `imports.invoices` đọc / tải / gỡ.
