-- ---------- 3. Chép đối tác đã dùng ở hợp đồng nhập (R18) — giữ id, không xóa Đại lý ----------
insert into public.import_suppliers (id, site_id, code, short_name, full_name, country, address, email, phone, note)
select s.id, s.site_id, '', s.short_name, coalesce(s.billing_name, ''), coalesce(s.country, ''), coalesce(s.address, ''),
       coalesce(s.email, ''), coalesce(s.phone, ''), 'Chép từ danh mục Đại lý (mig 0083)'
  from public.suppliers s
 where exists (select 1 from public.import_contracts c where c.supplier_id = s.id and c.site_id = s.site_id)
on conflict (id) do nothing;

