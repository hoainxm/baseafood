-- Mức độ rủi ro: 🟡 (chỉ thêm bảng) — mục 4 thay trọn ma trận mặc định như 0088.
-- ⚠ THỨ TỰ: tạo bucket → chạy SAU 0080, 0081, 0083 … 0089 (mỗi file thay trọn ma trận; 0087 đổi slug quản đốc).
