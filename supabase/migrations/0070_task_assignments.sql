-- Baseafood MES — 0070: GIAO VIỆC (task_assignments) cho màn "Việc của tôi" (/my-tasks)
--
-- Vì sao (chủ dự án 2026-10-19): app đã TỰ PHÁT HIỆN việc tồn (ngày nhập / SX chưa chốt,
-- BTP chờ duyệt, chưa gắn lô, kỳ cân đối chưa chốt… — lib/dataFlow.ts buildChainWarnings)
-- nhưng chỉ hiện ở Tổng quan, mà thủ kho / tổ trưởng không vào được Tổng quan. Việc lại chỉ
-- gắn VAI TRÒ — hai người cùng vai trò thấy cùng một việc, không biết ai phải làm. Bảng này
-- cho người điều phối GIAO một việc cho đúng một người, có hạn:
--   source 'system' — việc máy phát hiện (task_key = id cảnh báo, vd 'ccn|2026-10-12|Đông');
--                     tự hết khi sổ sửa xong, không cần bấm "Xong".
--   source 'manual' — việc giao tay (tiêu đề, hạn, màn cần mở); người nhận bấm "Xong".
-- Spec: docs/app-map/39-my-tasks.md.
--
-- KHÔNG có khóa ngoại tới user_profiles (assignee_id là text = auth uid): hồ sơ bị gắn lại /
-- xóa thì việc cũ vẫn đọc được nhờ assignee_name. Không gắn trigger chốt quyền 0065 — giao
-- việc là ghi chú điều phối, không phải sổ sách (lib/writePermissions.ts: task_assignments
-- = null); ai được GIAO do app kiểm (quyền my-tasks.create).
--
-- Kèm: ma trận mặc định default_role_permissions (0065) THAY TRỌN — thêm ô "my-tasks"
-- (Việc của tôi: xem / giao / sửa / thu hồi) cho kế toán (trưởng), quản đốc, phó QĐ. Chỉ
-- THÊM ô, không bớt ô nào của vai trò nào (test writePermissionsSql.test.ts so code ⇄ SQL).
-- Máy chủ chưa có trigger cho bảng này nên các ô mới chỉ để đồng bộ với app.
--
-- Mức độ rủi ro: 🟡 YELLOW — CHỈ THÊM 1 bảng; RLS theo khuôn 0057 (co_vai_tro()) ngay từ đầu,
-- revoke anon. Idempotent: chạy lại nhiều lần không lỗi. Câu lùi ở khối ROLLBACK cuối file.
-- ============================================================

create table if not exists public.task_assignments (
  id               text primary key,
  site_id          text not null default 'bsf1' references public.sites(id),
  source           text not null default 'manual' check (source in ('system', 'manual')),
  task_key         text not null default '',
  title            text not null check (length(btrim(title)) > 0),
  detail           text not null default '',
  path             text not null default '',
  workshop         text not null default '',
  task_date        date,
  due_date         date,
  assignee_id      text not null,
  assignee_name    text not null default '',
  assigned_by_id   text not null default '',
  assigned_by_name text not null default '',
  status           text not null default 'open' check (status in ('open', 'done', 'cancelled')),
  note             text not null default '',
  done_at          timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists task_assignments_assignee_idx on public.task_assignments (site_id, assignee_id, status);
create index if not exists task_assignments_task_key_idx on public.task_assignments (site_id, task_key);

drop trigger if exists task_assignments_touch_updated_at on public.task_assignments;
create trigger task_assignments_touch_updated_at
  before update on public.task_assignments
  for each row execute function public.cap_nhat_thoi_diem_sua(); -- naming-ok: hàm 0001

-- RLS: người có vai trò (co_vai_tro(), 0057) — bất biến: bảng mới phải siết, không mở anon.
alter table public.task_assignments enable row level security;
drop policy if exists task_assignments_select on public.task_assignments;
drop policy if exists task_assignments_insert on public.task_assignments;
drop policy if exists task_assignments_update on public.task_assignments;
drop policy if exists task_assignments_delete on public.task_assignments;
create policy task_assignments_select on public.task_assignments
  for select to authenticated using (public.co_vai_tro()); -- naming-ok: hàm 0057
create policy task_assignments_insert on public.task_assignments
  for insert to authenticated with check (public.co_vai_tro()); -- naming-ok: hàm 0057
create policy task_assignments_update on public.task_assignments
  for update to authenticated using (public.co_vai_tro()) with check (public.co_vai_tro()); -- naming-ok: hàm 0057
create policy task_assignments_delete on public.task_assignments
  for delete to authenticated using (public.co_vai_tro()); -- naming-ok: hàm 0057
revoke all on public.task_assignments from anon;
grant select, insert, update, delete on public.task_assignments to authenticated;

