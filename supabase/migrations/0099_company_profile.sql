--      = giá trị đang in trên invoice 236/26 (ba-spec 64 bảng kê).
--   2. Hàm `has_company_profile_permission(action)` (như `has_document_permission`, 0072).
--   3. RLS `company_profile`: xem = mọi người đăng nhập; thêm / sửa = `company-profile:update` (admin luôn được);
--      không xóa. Trigger nhật ký sửa (audit) như các bảng khác.
--   4. Bucket `company-assets` (logo) — TẠO TRƯỚC trên Dashboard (private, 5 MB). Đọc: mọi người đăng nhập;
--      ghi / xóa: `company-profile:update`.
--   5. 🔴 (chủ dự án đồng ý 2026-11-03) RLS `export_options`: dòng `list_kind = 'bank-account'` ghi được thêm bởi
--      người có `company-profile:update` (Kế toán trưởng không có quyền ghi Xuất khẩu). Danh sách khác giữ nguyên.
--   6. Thay trọn `default_role_permissions` (sinh từ DEFAULT_ROLE_PERMISSIONS — test canh): thêm `company-profile`
--      (Kế toán trưởng, Trưởng / Phó phòng KH: xem + sửa). Vai trò ĐÃ CHỈNH ở /roles không tự có ô này ⇒ cấp ở đó.
-- Idempotent. ⚠ Chạy SAU 0098. ⛔ Sau khi chạy ĐỪNG chạy lại 0073 / 0075 / 0079 / 0082 / 0083 (chèn ma trận cũ).
-- ⚠ Chưa chạy ⇒ tab Thông tin công ty dùng giá trị mặc định, chỉ xem; invoice in như cũ.
