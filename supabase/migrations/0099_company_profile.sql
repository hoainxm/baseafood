create unique index if not exists company_profile_site_idx on public.company_profile (site_id);

drop trigger if exists company_profile_touch_updated_at on public.company_profile;
create trigger company_profile_touch_updated_at
  before update on public.company_profile
  for each row execute function public.cap_nhat_thoi_diem_sua(); -- naming-ok: hàm 0001

-- ---------- 2. Hàm quyền ----------
create or replace function public.has_company_profile_permission(p_action text)
returns boolean
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_ctx jsonb := public.current_permission_context();
begin
  if coalesce((v_ctx->>'admin')::boolean, false) then return true; end if;
  return coalesce(v_ctx->'grants', '{}'::jsonb) ? ('company-profile:' || p_action);
end;
$$;
revoke all on function public.has_company_profile_permission(text) from public, anon;
grant execute on function public.has_company_profile_permission(text) to authenticated;

-- ---------- 3. RLS company_profile ----------
alter table public.company_profile enable row level security;
drop policy if exists company_profile_select on public.company_profile;
drop policy if exists company_profile_insert on public.company_profile;
drop policy if exists company_profile_update on public.company_profile;
create policy company_profile_select on public.company_profile for select to authenticated using (true);
-- App ghi bằng upsert ⇒ policy insert áp cả khi sửa (bài học 0065) ⇒ cùng điều kiện Sửa.
create policy company_profile_insert on public.company_profile for insert to authenticated
  with check (public.has_company_profile_permission('update'));
create policy company_profile_update on public.company_profile for update to authenticated
  using (public.has_company_profile_permission('update'))
  with check (public.has_company_profile_permission('update'));
revoke all on public.company_profile from anon;
grant select, insert, update on public.company_profile to authenticated;

do $$
begin
  if exists (select 1 from pg_proc where proname = 'ghi_vet_sua_truc_tiep') then -- naming-ok: hàm 0048
    execute 'drop trigger if exists company_profile_sql_audit on public.company_profile';
    execute 'create trigger company_profile_sql_audit after insert or update or delete on public.company_profile
             for each row execute function public.ghi_vet_sua_truc_tiep()'; -- naming-ok: hàm 0048
  end if;
end $$;

