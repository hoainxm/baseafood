-- ---------- 1. Bảng ----------
create table if not exists public.production_orders (
  id                     text primary key,
  site_id                text not null default 'bsf1' references public.sites(id),
  order_no               text not null default '',
  order_date             date,
  contract_id            text not null default '',
  contract_revision_id   text not null default '',
  contract_no            text not null default '',
  customer_name          text not null default '',
  market                 text not null default '',
  lot_code               text not null default '',
  production_dates       jsonb not null default '[]'::jsonb,
  delivery_date          date,
  shelf_life_months      integer not null default 24,
  requirements           jsonb not null default '{}'::jsonb,
  note                   text not null default '',
  status                 text not null default 'draft' check (status in ('draft', 'issued', 'cancelled')),
  issued_at              timestamptz,
  issued_by              text not null default '',
  revision_no            integer not null default 0,
  revision_reason        text not null default '',
  cancel_reason          text not null default '',
  stale_ack_revision_id  text not null default '',
  stale_ack_reason       text not null default '',
  created_by             text not null default '',
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);
create index if not exists production_orders_contract_idx on public.production_orders (site_id, contract_id);

create table if not exists public.production_order_lines (
  id                  text primary key,
  site_id             text not null default 'bsf1' references public.sites(id),
  order_id            text not null,
  line_no             integer not null default 1,
  contract_line_id    text not null default '',
  product_id          text not null default '',
  product_name        text not null default '',
  description         text not null default '',
  spec                text not null default '',
  unit_kind           text not null default 'carton' check (unit_kind in ('carton', 'bundle')),
  cartons_per_unit    numeric not null default 1,
  net_kg_per_carton   numeric,
  units               numeric,
  kg                  numeric,
  note                text not null default '',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index if not exists production_order_lines_order_idx on public.production_order_lines (site_id, order_id);

create table if not exists public.production_order_materials (
  id              text primary key,
  site_id         text not null default 'bsf1' references public.sites(id),
  order_id        text not null,
  order_line_id   text not null,
  receipt_id      text not null,
  import_line_id  text not null,
  label           text not null default '',
  kg              numeric,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists production_order_materials_order_idx on public.production_order_materials (site_id, order_id);
create index if not exists production_order_materials_receipt_idx on public.production_order_materials (site_id, receipt_id);

create table if not exists public.production_order_shipments (
  id            text primary key,
  site_id       text not null default 'bsf1' references public.sites(id),
  order_id      text not null,
  shipment_id   text not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists production_order_shipments_order_idx on public.production_order_shipments (site_id, order_id);
create index if not exists production_order_shipments_shipment_idx on public.production_order_shipments (site_id, shipment_id);

-- ---------- 2. RLS ----------
do $$
declare
  t text;
  w text := $q$public.has_export_permission('production-orders', 'create') or public.has_export_permission('production-orders', 'update')$q$;
  d text := $q$public.has_export_permission('production-orders', 'delete') or public.has_export_permission('production-orders', 'update')$q$;
  r text;
begin
  foreach t in array array['production_orders', 'production_order_lines', 'production_order_materials', 'production_order_shipments'] loop
    if t = 'production_orders' then
      -- Chỉ Xem ⇒ chỉ lệnh đã từng phát hành (nháp không lộ cho nơi nhận — ba-spec 48 AC-11).
      r := w || $q$ or (public.has_export_permission('production-orders', 'view') and issued_at is not null)$q$;
    else
      -- Bảng con: thấy khi thấy lệnh cha (RLS của production_orders áp vào truy vấn con).
      r := w || format(' or exists (select 1 from public.production_orders o where o.id = %I.order_id)', t);
    end if;
    execute format('drop trigger if exists %I on public.%I', t || '_touch_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.cap_nhat_thoi_diem_sua()', t || '_touch_updated_at', t); -- naming-ok: hàm 0001
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert', t);
    execute format('drop policy if exists %I on public.%I', t || '_update', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete', t);
    execute format('create policy %I on public.%I for select to authenticated using (%s)', t || '_select', t, r);
    execute format('create policy %I on public.%I for insert to authenticated with check (%s)', t || '_insert', t, w);
    execute format('create policy %I on public.%I for update to authenticated using (%s) with check (%s)', t || '_update', t, w, w);
    -- Lệnh không xóa cứng (R11 — hủy có lý do); dòng / NL / chuyến gắn xóa được khi sửa lệnh.
    if t = 'production_orders' then
      execute format('create policy %I on public.%I for delete to authenticated using (%s)', t || '_delete', t, $q$public.has_export_permission('production-orders', 'delete')$q$);
    else
      execute format('create policy %I on public.%I for delete to authenticated using (%s)', t || '_delete', t, d);
    end if;
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    if exists (select 1 from pg_proc where proname = 'ghi_vet_sua_truc_tiep') then -- naming-ok: hàm 0048
      execute format('drop trigger if exists %I on public.%I', t || '_sql_audit', t);
      execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.ghi_vet_sua_truc_tiep()', t || '_sql_audit', t); -- naming-ok: hàm 0048
    end if;
  end loop;
end $$;

