function CommandList({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.List>) {
  const ref = React.useRef<HTMLDivElement>(null)

  /* Khi danh sách nằm trong Dialog modal (Combobox trong hộp thoại ghi chuyến,
     cân đối…): Radix Dialog bật react-remove-scroll, nó nghe 'wheel' ở tầng
     `document` (bubble, non-passive) và preventDefault MỌI wheel có target nằm
     NGOÀI dialog. Popover danh sách được portal ra <body> nên nằm ngoài dialog →
     lăn chuột bị chặn, chỉ kéo thanh cuộn mới ăn. Chặn wheel bubble tới document
     để trả lại cuộn chuột (không đụng preventDefault nên cuộn mặc định vẫn chạy). */
  React.useEffect(() => {
    const el = ref.current
    if (!el) return
    const chanBubble = (e: WheelEvent) => e.stopPropagation()
    el.addEventListener("wheel", chanBubble)
    return () => el.removeEventListener("wheel", chanBubble)
  }, [])

  return (
    <CommandPrimitive.List
      ref={ref}
      data-slot="command-list"
      className={cn(
        /* KHÔNG dùng no-scrollbar: người dùng phải THẤY được là danh sách còn cuộn tiếp. */
        "min-h-0 flex-1 scroll-py-1 overflow-x-hidden overflow-y-auto outline-none [scrollbar-color:var(--color-border)_transparent] [scrollbar-width:auto]",
        className
      )}
      {...props}
    />
  )
}

