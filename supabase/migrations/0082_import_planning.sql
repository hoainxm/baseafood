-- ---------- 1. Quốc gia của nhà cung cấp ----------
alter table public.suppliers add column if not exists country text not null default '';

-- ---------- 2. Bảng ----------
create table if not exists public.import_contracts (
  id             text primary key,
  site_id        text not null default 'bsf1' references public.sites(id),
  supplier_id    text not null default '',
  supplier_name  text not null default '',
  contract_no    text not null check (length(btrim(contract_no)) > 0),
  signed_date    date,
  import_type    text not null default '' check (import_type in ('', 'export-production', 'trading', 'processing')),
  currency       text not null default 'USD',
  line_prices    jsonb not null default '{}'::jsonb,
  status         text not null default 'open' check (status in ('open', 'closed', 'cancelled')),
  close_reason   text not null default '',
  cancel_reason  text not null default '',
  note           text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists import_contracts_site_idx on public.import_contracts (site_id);
create unique index if not exists import_contracts_no_idx
  on public.import_contracts (site_id, supplier_id, lower(btrim(contract_no))) where status <> 'cancelled';

create table if not exists public.import_contract_lines (
  id            text primary key,
  site_id       text not null default 'bsf1' references public.sites(id),
  contract_id   text not null,
  line_no       integer not null default 0,
  product_name  text not null default '',
  kg            numeric,
  note          text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists import_contract_lines_contract_idx on public.import_contract_lines (site_id, contract_id);

create table if not exists public.import_receipts (
  id             text primary key,
  site_id        text not null default 'bsf1' references public.sites(id),
  contract_id    text not null,
  contract_no    text not null default '',
  supplier_name  text not null default '',
  arrival_date   date,
  expected_date  date,
  transport      text not null default '40RF' check (transport in ('20RF', '40RF', 'lcl')),
  container_no   text not null default '',
  bl_no          text not null default '',
  status         text not null default 'open' check (status in ('open', 'cancelled')),
  cancel_reason  text not null default '',
  note           text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists import_receipts_contract_idx on public.import_receipts (site_id, contract_id);

create table if not exists public.import_receipt_lines (
  id                text primary key,
  site_id           text not null default 'bsf1' references public.sites(id),
  receipt_id        text not null,
  contract_line_id  text not null,
  kg                numeric check (kg is null or kg >= 0),
  recorded_by       text not null default '',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index if not exists import_receipt_lines_receipt_idx on public.import_receipt_lines (site_id, receipt_id);

create table if not exists public.import_documents (
  id              text primary key,
  site_id         text not null default 'bsf1' references public.sites(id),
  receipt_id      text not null,
  kind            text not null default 'other' check (kind in ('commercial-invoice', 'packing-list', 'import-declaration', 'certificate-of-origin', 'quarantine-certificate', 'bill-of-lading', 'other')),
  custom_name     text not null default '',
  doc_no          text not null default '',
  doc_date        date,
  import_type     text not null default '' check (import_type in ('', 'export-production', 'trading', 'processing')),
  not_applicable  boolean not null default false,
  na_reason       text not null default '',
  note            text not null default '',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists import_documents_receipt_idx on public.import_documents (site_id, receipt_id);

create table if not exists public.import_files (
  id           text primary key,
  site_id      text not null default 'bsf1' references public.sites(id),
  contract_id  text not null default '',
  receipt_id   text not null default '',
  document_id  text not null default '',
  path         text not null default '',
  file_name    text not null default '',
  uploaded_by  text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists import_files_contract_idx on public.import_files (site_id, contract_id);

-- ---------- 3. Trigger sửa giờ + RLS + ghi vết ----------
-- Đọc / ghi / xóa theo ô quyền (ba-spec 45 R9). insert = update vì app ghi bằng upsert.
do $$
declare
  t text; r text; w text; d text;
begin
  for t, r, w, d in
    select * from (values
      ('import_contracts',
       $q$public.has_export_permission('import-plans', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete')$q$),
      ('import_contract_lines',
       $q$public.has_export_permission('import-plans', 'view') or public.has_export_permission('import-plans.receiving', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete') or public.has_export_permission('import-plans', 'update')$q$),
      ('import_receipts',
       $q$public.has_export_permission('import-plans', 'view') or public.has_export_permission('import-plans.receiving', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete')$q$),
      ('import_receipt_lines',
       $q$public.has_export_permission('import-plans', 'view') or public.has_export_permission('import-plans.receiving', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update') or public.has_export_permission('import-plans.receiving', 'create') or public.has_export_permission('import-plans.receiving', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete') or public.has_export_permission('import-plans', 'update')$q$),
      ('import_documents',
       $q$public.has_export_permission('import-plans', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete') or public.has_export_permission('import-plans', 'update')$q$),
      ('import_files',
       $q$public.has_export_permission('import-plans', 'view')$q$,
       $q$public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')$q$,
       $q$public.has_export_permission('import-plans', 'delete') or public.has_export_permission('import-plans', 'update')$q$)
    ) as x(t, r, w, d)
  loop
    execute format('drop trigger if exists %I on public.%I', t || '_touch_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.cap_nhat_thoi_diem_sua()', t || '_touch_updated_at', t); -- naming-ok: hàm 0001
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert', t);
    execute format('drop policy if exists %I on public.%I', t || '_update', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete', t);
    execute format('create policy %I on public.%I for select to authenticated using (%s)', t || '_select', t, r);
    execute format('create policy %I on public.%I for insert to authenticated with check (%s)', t || '_insert', t, w);
    execute format('create policy %I on public.%I for update to authenticated using (%s) with check (%s)', t || '_update', t, w, w);
    execute format('create policy %I on public.%I for delete to authenticated using (%s)', t || '_delete', t, d);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    if exists (select 1 from pg_proc where proname = 'ghi_vet_sua_truc_tiep') then -- naming-ok: hàm 0048
      execute format('drop trigger if exists %I on public.%I', t || '_sql_audit', t);
      execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.ghi_vet_sua_truc_tiep()', t || '_sql_audit', t); -- naming-ok: hàm 0048
    end if;
  end loop;
end $$;

-- ---------- 4. Bucket `import-files` (chủ dự án tạo trước trên Dashboard) ----------
-- Đường dẫn: <site>/import-files/<id hợp đồng>/<id>-<tên file>. Chỉ người có import-plans đọc / tải /
-- gỡ (thủ kho không đọc chứng từ). Không có policy update (file không ghi đè).
do $$
begin
  if not exists (select 1 from storage.buckets where id = 'import-files') then
    raise notice 'CHƯA có bucket "import-files" — tạo trên Dashboard (private, 20 MB) rồi chạy lại file này.';
  end if;
end $$;

drop policy if exists import_files_bucket_select on storage.objects;
drop policy if exists import_files_bucket_insert on storage.objects;
drop policy if exists import_files_bucket_delete on storage.objects;
create policy import_files_bucket_select on storage.objects
  for select to authenticated using (bucket_id = 'import-files' and public.has_export_permission('import-plans', 'view'));
create policy import_files_bucket_insert on storage.objects
  for insert to authenticated with check (bucket_id = 'import-files' and (public.has_export_permission('import-plans', 'create') or public.has_export_permission('import-plans', 'update')));
create policy import_files_bucket_delete on storage.objects
  for delete to authenticated using (bucket_id = 'import-files' and (public.has_export_permission('import-plans', 'delete') or public.has_export_permission('import-plans', 'update')));

