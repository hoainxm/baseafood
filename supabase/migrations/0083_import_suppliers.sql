-- ---------- 1. Bảng ----------
create table if not exists public.import_suppliers (
  id            text primary key,
  site_id       text not null default 'bsf1' references public.sites(id),
  code          text not null default '',
  short_name    text not null default '',
  full_name     text not null default '',
  country       text not null default '',
  address       text not null default '',
  tax_id        text not null default '',
  main_products text not null default '',
  loading_port  text not null default '',
  contact_name  text not null default '',
  contact_title text not null default '',
  email         text not null default '',
  phone         text not null default '',
  website       text not null default '',
  bank_name     text not null default '',
  bank_account  text not null default '',
  swift_code    text not null default '',
  bank_address  text not null default '',
  status        text not null default 'active' check (status in ('active', 'inactive')),
  note          text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists import_suppliers_site_idx on public.import_suppliers (site_id);

drop trigger if exists import_suppliers_touch_updated_at on public.import_suppliers;
create trigger import_suppliers_touch_updated_at
  before update on public.import_suppliers
  for each row execute function public.cap_nhat_thoi_diem_sua(); -- naming-ok: hàm 0001

-- ---------- 2. RLS ----------
alter table public.import_suppliers enable row level security;
drop policy if exists import_suppliers_select on public.import_suppliers;
drop policy if exists import_suppliers_insert on public.import_suppliers;
drop policy if exists import_suppliers_update on public.import_suppliers;
drop policy if exists import_suppliers_delete on public.import_suppliers;
create policy import_suppliers_select on public.import_suppliers for select to authenticated
  using (public.has_export_permission('catalog.import-suppliers', 'view') or public.has_export_permission('import-plans', 'view'));
create policy import_suppliers_insert on public.import_suppliers for insert to authenticated
  with check (public.has_export_permission('catalog.import-suppliers', 'create') or public.has_export_permission('catalog.import-suppliers', 'update'));
create policy import_suppliers_update on public.import_suppliers for update to authenticated
  using (public.has_export_permission('catalog.import-suppliers', 'create') or public.has_export_permission('catalog.import-suppliers', 'update'))
  with check (public.has_export_permission('catalog.import-suppliers', 'create') or public.has_export_permission('catalog.import-suppliers', 'update'));
create policy import_suppliers_delete on public.import_suppliers for delete to authenticated
  using (public.has_export_permission('catalog.import-suppliers', 'delete'));

revoke all on public.import_suppliers from anon;
grant select, insert, update, delete on public.import_suppliers to authenticated;

