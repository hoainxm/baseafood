-- ---------- 1. Bảng ----------
create table if not exists public.supplier_invoices (
  id                    text primary key,
  site_id               text not null default 'bsf1' references public.sites(id),
  supplier_name         text not null default '',
  accounting_code       text not null default '',
  invoice_no            text not null default '',
  invoice_year          integer not null default 0,
  invoice_symbol        text not null default '',
  issue_date            date,
  posting_date          date,
  voucher_no            text not null default '',
  seller_tax_id         text not null default '',
  subtotal              numeric,
  vat_amount            numeric,
  total_amount          numeric,
  classification        text not null default 'trip' check (classification in ('trip', 'not-trip')),
  classification_note   text not null default '',
  pdf_lines             jsonb not null default '[]'::jsonb,
  file_path             text not null default '',
  file_name             text not null default '',
  note                  text not null default '',
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);
create index if not exists supplier_invoices_site_idx on public.supplier_invoices (site_id, supplier_name, invoice_no);

create table if not exists public.supplier_invoice_lines (
  id                  text primary key,
  site_id             text not null default 'bsf1' references public.sites(id),
  invoice_id          text not null default '',
  delivery_date       date,
  material_code       text not null default '',
  quantity_kg         numeric not null default 0,
  unit_price          numeric not null default 0,
  amount              numeric not null default 0,
  driver_name         text not null default '',
  license_plate       text not null default '',
  row_key             text not null default '',
  trip_line_id        text not null default '',
  resolution          text not null default '' check (resolution in ('', 'updated', 'explained')),
  resolution_reason   text not null default '',
  resolved_by         text not null default '',
  resolved_at         text not null default '',
  missing_from_file   boolean not null default false,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index if not exists supplier_invoice_lines_invoice_idx on public.supplier_invoice_lines (site_id, invoice_id);
create index if not exists supplier_invoice_lines_trip_idx on public.supplier_invoice_lines (site_id, trip_line_id);

create table if not exists public.accounting_code_maps (
  id            text primary key,
  site_id       text not null default 'bsf1' references public.sites(id),
  kind          text not null default 'supplier' check (kind in ('supplier', 'material')),
  code          text not null default '',
  target_name   text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists accounting_code_maps_site_idx on public.accounting_code_maps (site_id, kind, code);

-- ---------- 2. RLS ----------
do $$
declare
  t text;
  r text := $q$public.has_export_permission('imports.invoices', 'view') or public.has_export_permission('imports', 'view')$q$;
  w text := $q$public.has_export_permission('imports.invoices', 'create') or public.has_export_permission('imports.invoices', 'update')$q$;
  d text := $q$public.has_export_permission('imports.invoices', 'delete')$q$;
begin
  foreach t in array array['supplier_invoices', 'supplier_invoice_lines', 'accounting_code_maps'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_touch_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.cap_nhat_thoi_diem_sua()', t || '_touch_updated_at', t); -- naming-ok: hàm 0001
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert', t);
    execute format('drop policy if exists %I on public.%I', t || '_update', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete', t);
    execute format('create policy %I on public.%I for select to authenticated using (%s)', t || '_select', t, r);
    execute format('create policy %I on public.%I for insert to authenticated with check (%s)', t || '_insert', t, w);
    execute format('create policy %I on public.%I for update to authenticated using (%s) with check (%s)', t || '_update', t, w, w);
    execute format('create policy %I on public.%I for delete to authenticated using (%s)', t || '_delete', t, d);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    if exists (select 1 from pg_proc where proname = 'ghi_vet_sua_truc_tiep') then -- naming-ok: hàm 0048
      execute format('drop trigger if exists %I on public.%I', t || '_sql_audit', t);
      execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.ghi_vet_sua_truc_tiep()', t || '_sql_audit', t); -- naming-ok: hàm 0048
    end if;
  end loop;
end $$;

-- ---------- 3. Bucket `supplier-invoice-files` (chủ dự án tạo trước trên Dashboard) ----------
-- Đường dẫn: <site>/supplier-invoice-files/<năm>/<id>-<tên file>. Không có policy update (file không ghi đè).
do $$
begin
  if not exists (select 1 from storage.buckets where id = 'supplier-invoice-files') then
    raise notice 'CHƯA có bucket "supplier-invoice-files" — tạo trên Dashboard (private, 20 MB) rồi chạy lại file này.';
  end if;
end $$;

drop policy if exists supplier_invoice_files_select on storage.objects;
drop policy if exists supplier_invoice_files_insert on storage.objects;
drop policy if exists supplier_invoice_files_delete on storage.objects;
create policy supplier_invoice_files_select on storage.objects
  for select to authenticated using (bucket_id = 'supplier-invoice-files' and public.has_export_permission('imports.invoices', 'view'));
create policy supplier_invoice_files_insert on storage.objects
  for insert to authenticated with check (bucket_id = 'supplier-invoice-files' and (public.has_export_permission('imports.invoices', 'create') or public.has_export_permission('imports.invoices', 'update')));
create policy supplier_invoice_files_delete on storage.objects
  for delete to authenticated using (bucket_id = 'supplier-invoice-files' and (public.has_export_permission('imports.invoices', 'delete') or public.has_export_permission('imports.invoices', 'update')));

